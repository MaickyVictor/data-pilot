import streamlit as st
import plotly.express as px
import pandas as pd
import os, json
from dotenv import load_dotenv
from openai import OpenAI
import metrics

load_dotenv()
client = OpenAI(base_url="https://openrouter.ai/api/v1", api_key=os.getenv("OPENROUTER_API_KEY"))

st.set_page_config(page_title="Data Pilot", layout="wide")
st.sidebar.title("Data Pilot")
menu = st.sidebar.radio("Menu", ["Painel", "Conversa"])

df_clean = pd.read_csv("data/sales_clean.csv", sep=";", decimal=",", parse_dates=["data"])
cat_opcoes = ["Todas"] + sorted(df_clean["categoria"].unique().tolist())
cat_sel = st.sidebar.selectbox("Filtrar por categoria", cat_opcoes)
filtro = None if cat_sel=="Todas" else cat_sel

if menu=="Painel":
    st.title("Painel de Vendas")
    c1,c2,c3,c4 = st.columns(4)
    c1.metric("Receita Total", f"R$ {metrics.get_receita_total(filtro):,.2f}")
    c2.metric("Pedidos", metrics.get_total_pedidos(filtro))
    c3.metric("Ticket Médio", f"R$ {metrics.get_ticket_medio(filtro):,.2f}")
    c4.metric("Receita Média / Cliente", f"R$ {metrics.get_receita_media_por_cliente(filtro):,.2f}")

    mensal = metrics.get_receita_mensal(filtro)
    df_m = pd.DataFrame(list(mensal.items()), columns=["mes","receita"]).sort_values("mes")
    fig1 = px.bar(df_m, x="mes", y="receita", title="Receita Mensal")
    st.plotly_chart(fig1, use_container_width=True)

    top_cidades = metrics.get_top_cidades()
    df_c = pd.DataFrame(list(top_cidades.items()), columns=["cidade","receita"])
    fig2 = px.bar(df_c, x="cidade", y="receita", title="Top 5 Cidades que mais vendem - SUA MELHORIA")
    st.plotly_chart(fig2, use_container_width=True)

else:
    st.title("Converse com os dados")
    st.caption("Ex: Qual a receita total? Qual o ticket médio de eletronicos? Qual a receita média por cliente?")

    tools = [
        {"type":"function","function":{"name":"get_receita_total","description":"Receita total, filtra por categoria se informado","parameters":{"type":"object","properties":{"categoria":{"type":"string"}},"required":[]}}},
        {"type":"function","function":{"name":"get_total_pedidos","description":"Total de pedidos concluídos","parameters":{"type":"object","properties":{"categoria":{"type":"string"}},"required":[]}}},
        {"type":"function","function":{"name":"get_ticket_medio","description":"Ticket médio","parameters":{"type":"object","properties":{"categoria":{"type":"string"}},"required":[]}}},
        {"type":"function","function":{"name":"get_receita_media_por_cliente","description":"Receita média por cliente único - calcula receita total dividido por clientes únicos","parameters":{"type":"object","properties":{"categoria":{"type":"string"}},"required":[]}}},
        {"type":"function","function":{"name":"get_top_cidades","description":"Retorna as 5 cidades que mais vendem","parameters":{"type":"object","properties":{"n":{"type":"integer"}},"required":[]}}},
    ]

    if "msgs" not in st.session_state: st.session_state.msgs=[]
    for m in st.session_state.msgs: st.chat_message(m["role"]).write(m["content"])

    if pergunta := st.chat_input("Digite sua pergunta"):
        st.session_state.msgs.append({"role":"user","content":pergunta})
        st.chat_message("user").write(pergunta)

        resp = client.chat.completions.create(model=os.getenv("MODEL"), messages=[{"role":"system","content":"Você é analista. Use apenas as ferramentas para números. Nunca invente."}]+st.session_state.msgs, tools=tools, tool_choice="auto")
        msg = resp.choices[0].message

        if msg.tool_calls:
            for tc in msg.tool_calls:
                nome = tc.function.name
                args = json.loads(tc.function.arguments or "{}")
                valor = getattr(metrics, nome)(**args)
                # Segunda chamada pra explicar
                final = client.chat.completions.create(model=os.getenv("MODEL"), messages=[{"role":"system","content":f"Dado calculado pelo Python: {valor}. Explique em PT-BR de forma clara. Se for top cidades, liste."},{"role":"user","content":pergunta}])
                texto = final.choices[0].message.content
                st.chat_message("assistant").write(texto)
                st.session_state.msgs.append({"role":"assistant","content":texto})
        else:
            st.chat_message("assistant").write(msg.content)
            st.session_state.msgs.append({"role":"assistant","content":msg.content})